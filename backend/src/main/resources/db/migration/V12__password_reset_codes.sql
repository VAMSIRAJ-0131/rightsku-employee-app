-- Self-service password reset ("Forgot password"). Additive only.
--
-- A reset code is emailed to the account's registered address. Only a BCrypt
-- hash of the code is stored, never the code itself. A code works once, for
-- a short time, and for a few attempts; asking for a new code ends any older
-- unused one (see PasswordResetService).

CREATE TABLE password_reset_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    code_hash VARCHAR(100) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    -- Set when the code is used, or when a newer code replaces it.
    used_at TIMESTAMPTZ,
    failed_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_password_reset_codes_user_created ON password_reset_codes (user_id, created_at DESC);
