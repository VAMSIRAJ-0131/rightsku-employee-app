-- Weekly-off schedule replacement, notification links and clearing, employee
-- gender and name prefix, and the company profile with office addresses.
-- Additive only: new nullable columns and new tables. No existing row is
-- changed or deleted, and no company data is filled in (HR enters it).

-- 1. A schedule saved from a Monday replaces the employee's schedules that
--    start later. Those rows are kept for history and only marked replaced,
--    so they stop applying.
ALTER TABLE employee_work_schedules
    ADD COLUMN replaced_at TIMESTAMPTZ,
    ADD COLUMN replaced_by BIGINT REFERENCES app_users(id);

-- 2. Notifications: what each one is about (so tapping it opens that record)
--    and when the person cleared it from their list. Clearing hides the
--    notification only; the leave, timesheet, payslip or other record it
--    talks about is never touched.
ALTER TABLE notifications
    ADD COLUMN link_type VARCHAR(30)
        CHECK (link_type IN ('LEAVE_REQUEST', 'TIMESHEET_WEEK', 'DOCUMENT', 'SCHEDULE', 'COMP_OFF_REQUEST')),
    ADD COLUMN link_key VARCHAR(40),
    ADD COLUMN cleared_at TIMESTAMPTZ;
CREATE INDEX ix_notifications_user_visible ON notifications (user_id, created_at DESC) WHERE cleared_at IS NULL;

-- 3. The company: one profile row (name and phone) and its office addresses.
CREATE TABLE company_profile (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    name VARCHAR(150) NOT NULL CHECK (length(trim(name)) > 0),
    phone VARCHAR(30),
    updated_by BIGINT REFERENCES app_users(id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE company_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label VARCHAR(60) NOT NULL CHECK (length(trim(label)) > 0),
    address VARCHAR(300) NOT NULL CHECK (length(trim(address)) > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT REFERENCES app_users(id),
    updated_by BIGINT REFERENCES app_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. Employees: gender, name prefix and the office address on their ID card.
--    All optional, so existing employees stay valid with no value.
ALTER TABLE employees
    ADD COLUMN gender VARCHAR(10) CHECK (gender IN ('MALE', 'FEMALE')),
    ADD COLUMN name_prefix VARCHAR(5) CHECK (name_prefix IN ('MR', 'MS', 'MRS')),
    ADD COLUMN company_address_id BIGINT REFERENCES company_addresses(id);
