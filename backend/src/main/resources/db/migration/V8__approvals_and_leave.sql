-- HR review of timesheets, leave balances and leave requests.
-- Additive only: new nullable columns and new tables. No existing row,
-- constraint or status value is changed.

-- Who reviewed a timesheet entry, when, and the note shown to the employee.
ALTER TABLE timesheet_entries
    ADD COLUMN reviewed_by BIGINT REFERENCES app_users(id),
    ADD COLUMN reviewed_at TIMESTAMPTZ,
    ADD COLUMN review_note VARCHAR(500);

-- Leave left per employee and leave type, set by HR (in days, half days allowed).
-- Approving a leave request takes its days off this balance.
CREATE TABLE leave_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    leave_type VARCHAR(20) NOT NULL CHECK (leave_type IN ('CASUAL', 'SICK', 'EARNED')),
    balance_days NUMERIC(5, 1) NOT NULL DEFAULT 0
        CHECK (balance_days >= 0 AND balance_days <= 365 AND balance_days * 2 = trunc(balance_days * 2)),
    updated_by BIGINT REFERENCES app_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_leave_balances_type UNIQUE (employee_id, leave_type)
);

-- Leave applications. days = working days between start and end (weekly
-- offs and company holidays are not counted), worked out by the server.
CREATE TABLE leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    leave_type VARCHAR(20) NOT NULL CHECK (leave_type IN ('CASUAL', 'SICK', 'EARNED')),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    days NUMERIC(5, 1) NOT NULL CHECK (days > 0),
    reason VARCHAR(500) NOT NULL CHECK (length(trim(reason)) > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    reviewed_by BIGINT REFERENCES app_users(id),
    reviewed_at TIMESTAMPTZ,
    review_note VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_leave_requests_dates CHECK (end_date >= start_date)
);

CREATE INDEX idx_leave_requests_employee ON leave_requests (employee_id, status);
CREATE INDEX idx_leave_requests_status ON leave_requests (status);
