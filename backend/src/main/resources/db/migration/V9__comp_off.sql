-- Comp-Off: a fourth leave type, plus a history of every Comp-Off balance change.
-- Additive: no row is changed or deleted. The two leave-type checks from V8 are
-- replaced by wider ones that still allow every value the old ones allowed.

ALTER TABLE leave_balances DROP CONSTRAINT leave_balances_leave_type_check;
ALTER TABLE leave_balances ADD CONSTRAINT ck_leave_balances_leave_type
    CHECK (leave_type IN ('CASUAL', 'SICK', 'EARNED', 'COMP_OFF'));

ALTER TABLE leave_requests DROP CONSTRAINT leave_requests_leave_type_check;
ALTER TABLE leave_requests ADD CONSTRAINT ck_leave_requests_leave_type
    CHECK (leave_type IN ('CASUAL', 'SICK', 'EARNED', 'COMP_OFF'));

-- Every change to a Comp-Off balance, newest last: HR's manual additions and
-- deductions (always with a reason) and the days taken off when HR approves a
-- Comp-Off leave request. Rows are never updated or deleted by the app.
CREATE TABLE leave_balance_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    leave_type VARCHAR(20) NOT NULL CHECK (leave_type IN ('COMP_OFF')),
    source VARCHAR(20) NOT NULL CHECK (source IN ('MANUAL', 'LEAVE_APPROVED')),
    change_days NUMERIC(5, 1) NOT NULL
        CHECK (change_days <> 0 AND change_days * 2 = trunc(change_days * 2)),
    balance_before NUMERIC(5, 1) NOT NULL CHECK (balance_before >= 0 AND balance_before <= 365),
    balance_after NUMERIC(5, 1) NOT NULL CHECK (balance_after >= 0 AND balance_after <= 365),
    reason VARCHAR(500) NOT NULL CHECK (length(trim(reason)) > 0),
    -- Set for an approval: one approval can take days off only once.
    leave_request_id BIGINT REFERENCES leave_requests(id),
    -- Sent by the app with each manual change: the same change sent twice
    -- (double tap, retry after a lost reply) is applied only once.
    request_key VARCHAR(64),
    created_by BIGINT REFERENCES app_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_leave_balance_adjustments_math CHECK (balance_after = balance_before + change_days),
    CONSTRAINT ck_leave_balance_adjustments_source CHECK (
        (source = 'MANUAL' AND request_key IS NOT NULL AND leave_request_id IS NULL)
        OR (source = 'LEAVE_APPROVED' AND leave_request_id IS NOT NULL AND change_days < 0)),
    CONSTRAINT ux_leave_balance_adjustments_request UNIQUE (leave_request_id),
    CONSTRAINT ux_leave_balance_adjustments_key UNIQUE (request_key)
);

CREATE INDEX idx_leave_balance_adjustments_employee
    ON leave_balance_adjustments (employee_id, leave_type, created_at);
