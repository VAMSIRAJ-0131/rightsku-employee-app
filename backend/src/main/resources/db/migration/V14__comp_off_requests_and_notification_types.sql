-- Comp-Off requests from employees, credited by HR approval, and three more
-- notification types. Additive: one new table and one new nullable column.
-- No existing row is changed or deleted; each check that is replaced is
-- replaced by a wider one that still allows every row the old one allowed.

-- An employee asks for Comp-Off for one past weekly off or company holiday
-- they worked on (full or half day). HR approves (the days are credited to
-- the Comp-Off balance once) or rejects (nothing is credited).
CREATE TABLE comp_off_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    work_date DATE NOT NULL,
    days NUMERIC(2, 1) NOT NULL CHECK (days IN (0.5, 1.0)),
    reason VARCHAR(500) NOT NULL CHECK (length(trim(reason)) > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    reviewed_by BIGINT REFERENCES app_users(id),
    reviewed_at TIMESTAMPTZ,
    review_note VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_comp_off_requests_decided CHECK ((status = 'PENDING') = (reviewed_at IS NULL))
);

-- At most one pending or approved request per employee and day: the same day
-- can never be credited twice. A rejected request does not block a new one.
CREATE UNIQUE INDEX ux_comp_off_requests_active_day
    ON comp_off_requests (employee_id, work_date) WHERE status <> 'REJECTED';
CREATE INDEX idx_comp_off_requests_status ON comp_off_requests (status, created_at);

-- The Comp-Off history also records each approved request's credit.
ALTER TABLE leave_balance_adjustments
    ADD COLUMN comp_off_request_id BIGINT REFERENCES comp_off_requests(id);
-- One approval can credit only once.
ALTER TABLE leave_balance_adjustments
    ADD CONSTRAINT ux_leave_balance_adjustments_comp_off_request UNIQUE (comp_off_request_id);

ALTER TABLE leave_balance_adjustments DROP CONSTRAINT leave_balance_adjustments_source_check;
ALTER TABLE leave_balance_adjustments ADD CONSTRAINT ck_leave_balance_adjustments_source_value
    CHECK (source IN ('MANUAL', 'LEAVE_APPROVED', 'COMP_OFF_EARNED'));

ALTER TABLE leave_balance_adjustments DROP CONSTRAINT ck_leave_balance_adjustments_source;
ALTER TABLE leave_balance_adjustments ADD CONSTRAINT ck_leave_balance_adjustments_source CHECK (
    (source = 'MANUAL' AND request_key IS NOT NULL AND leave_request_id IS NULL
        AND comp_off_request_id IS NULL)
    OR (source = 'LEAVE_APPROVED' AND leave_request_id IS NOT NULL AND change_days < 0
        AND comp_off_request_id IS NULL)
    OR (source = 'COMP_OFF_EARNED' AND comp_off_request_id IS NOT NULL AND change_days > 0
        AND leave_request_id IS NULL AND request_key IS NULL));

-- New notifications: weekly-off schedule changes and Comp-Off decisions.
ALTER TABLE notifications DROP CONSTRAINT notifications_type_check;
ALTER TABLE notifications ADD CONSTRAINT ck_notifications_type
    CHECK (type IN ('LEAVE_APPROVED', 'LEAVE_REJECTED', 'TIMESHEET_APPROVED', 'TIMESHEET_REJECTED',
                    'PAYSLIP_PUBLISHED', 'DOCUMENT_PUBLISHED',
                    'SCHEDULE_CHANGED', 'COMP_OFF_APPROVED', 'COMP_OFF_REJECTED'));
