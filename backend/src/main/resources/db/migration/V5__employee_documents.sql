-- Employee documents uploaded by HR (offer letters, experience letters,
-- payslips and Form 16). Additive only: new tables, nothing existing changes.
--
-- The file itself is kept in a separate table, so listing documents never
-- reads file contents. Files are stored inside PostgreSQL (BYTEA), so they
-- are included in normal database backups. Only the API can read them, and
-- the API checks who is asking (see DocumentService).

CREATE TABLE employee_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    doc_type VARCHAR(30) NOT NULL
        CHECK (doc_type IN ('OFFER_LETTER', 'EXPERIENCE_LETTER', 'PAYSLIP', 'FORM_16')),
    -- Payslip month (2026-09) or Form 16 financial year (2025-26); empty for letters.
    period VARCHAR(7),
    title VARCHAR(150) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL
        CHECK (content_type IN ('application/pdf', 'image/png', 'image/jpeg')),
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
    sha256 VARCHAR(64) NOT NULL,
    -- 1 for the first upload, +1 each time HR replaces the file.
    version INTEGER NOT NULL DEFAULT 1 CHECK (version >= 1),
    uploaded_by BIGINT REFERENCES app_users(id),
    updated_by BIGINT REFERENCES app_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_employee_documents_period CHECK (
        (doc_type = 'PAYSLIP' AND period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$')
        OR (doc_type = 'FORM_16' AND period ~ '^[0-9]{4}-[0-9]{2}$')
        OR (doc_type IN ('OFFER_LETTER', 'EXPERIENCE_LETTER') AND period IS NULL)
    )
);

-- One document per employee, type and period (for example one payslip per
-- month). A corrected file replaces the existing one instead.
CREATE UNIQUE INDEX ux_employee_documents_slot
    ON employee_documents (employee_id, doc_type, COALESCE(period, ''));

CREATE INDEX idx_employee_documents_updated_at ON employee_documents (updated_at);

CREATE TABLE employee_document_files (
    document_id BIGINT PRIMARY KEY REFERENCES employee_documents(id),
    content BYTEA NOT NULL
);
