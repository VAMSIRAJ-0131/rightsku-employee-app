-- Weekly timesheets: a saved draft for each week, then one submission for
-- the whole week. Additive only: two new tables. timesheet_entries (V6) and
-- every existing entry stay exactly as they are; a submitted week still
-- creates one PENDING row per day there, so the HR approval module will see
-- old and new entries the same way.

-- One row per employee per week (week_start is always a Monday).
-- DRAFT: the employee is still filling the week and can change it.
-- SUBMITTED: sent for approval; the week can no longer be saved or submitted.
CREATE TABLE timesheet_weeks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    week_start DATE NOT NULL CHECK (EXTRACT(ISODOW FROM week_start) = 1),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'SUBMITTED')),
    description VARCHAR(500),
    submitted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_timesheet_weeks_week UNIQUE (employee_id, week_start),
    CONSTRAINT ck_timesheet_weeks_submitted CHECK (status = 'DRAFT' OR submitted_at IS NOT NULL)
);

-- The hours of a draft week, one row per day. Removed when the week is
-- submitted (the submitted hours are then in timesheet_entries).
CREATE TABLE timesheet_draft_days (
    week_id BIGINT NOT NULL REFERENCES timesheet_weeks(id) ON DELETE CASCADE,
    work_date DATE NOT NULL,
    hours NUMERIC(4, 2) NOT NULL CHECK (hours > 0 AND hours <= 24),
    PRIMARY KEY (week_id, work_date)
);
