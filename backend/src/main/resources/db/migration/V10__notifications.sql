-- In-app notifications for one account (the employee's app_users row).
-- Additive only: a new table, nothing existing changes.
--
-- Rows are written by the backend when HR acts (leave or timesheet decided,
-- document or payslip published). The only change the app makes afterwards
-- is setting read_at; rows are never edited otherwise.

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    type VARCHAR(30) NOT NULL
        CHECK (type IN ('LEAVE_APPROVED', 'LEAVE_REJECTED', 'TIMESHEET_APPROVED', 'TIMESHEET_REJECTED',
                        'PAYSLIP_PUBLISHED', 'DOCUMENT_PUBLISHED')),
    title VARCHAR(150) NOT NULL CHECK (length(trim(title)) > 0),
    message VARCHAR(500) NOT NULL,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- The app lists the newest notifications of one account and counts its unread ones.
CREATE INDEX ix_notifications_user_created ON notifications (user_id, created_at DESC, id DESC);
CREATE INDEX ix_notifications_user_unread ON notifications (user_id) WHERE read_at IS NULL;
