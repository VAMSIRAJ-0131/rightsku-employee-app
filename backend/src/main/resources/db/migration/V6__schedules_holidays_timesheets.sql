-- Working schedules, the company holiday calendar and timesheet entries.
-- Additive only: new tables, nothing existing changes.

-- HR-controlled working schedule per employee. A schedule applies from its
-- effective_from date until the next schedule for that employee starts, so
-- changing a schedule never rewrites earlier dates. An employee without any
-- row uses the company default (app.schedule.* settings).
--
-- weekly_off_mask: one bit per weekly off day (Monday = 1, Tuesday = 2,
-- Wednesday = 4, Thursday = 8, Friday = 16, Saturday = 32, Sunday = 64).
-- 127 (every day off) is not allowed: at least one working day is required.
CREATE TABLE employee_work_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    effective_from DATE NOT NULL,
    weekly_off_mask SMALLINT NOT NULL CHECK (weekly_off_mask BETWEEN 0 AND 126),
    hours_per_day NUMERIC(4, 2) NOT NULL CHECK (hours_per_day > 0 AND hours_per_day <= 24),
    created_by BIGINT REFERENCES app_users(id),
    updated_by BIGINT REFERENCES app_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_employee_work_schedules_start UNIQUE (employee_id, effective_from)
);

-- Company-wide holidays, managed by HR. One holiday per date.
CREATE TABLE company_holidays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holiday_date DATE NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) > 0),
    created_by BIGINT REFERENCES app_users(id),
    updated_by BIGINT REFERENCES app_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Daily timesheet entries submitted by employees. One entry per employee
-- per date. Approval by HR is a later module; new entries are PENDING.
CREATE TABLE timesheet_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    work_date DATE NOT NULL,
    hours NUMERIC(4, 2) NOT NULL CHECK (hours > 0 AND hours <= 24),
    description VARCHAR(500) NOT NULL CHECK (length(trim(description)) > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_timesheet_entries_day UNIQUE (employee_id, work_date)
);

CREATE INDEX idx_timesheet_entries_status ON timesheet_entries (status);
