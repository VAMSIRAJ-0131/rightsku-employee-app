-- Stage 1: employees can cancel a pending request, and ask HR to change
-- their personal details. Additive only: existing rows are not changed.

-- 1. Leave and Comp-Off requests can be CANCELLED by the employee while
--    still pending. A cancelled request holds no days and blocks nothing.
ALTER TABLE leave_requests DROP CONSTRAINT leave_requests_status_check;
ALTER TABLE leave_requests ADD CONSTRAINT leave_requests_status_check
    CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'));
ALTER TABLE leave_requests ADD COLUMN cancelled_at TIMESTAMPTZ;

ALTER TABLE comp_off_requests DROP CONSTRAINT comp_off_requests_status_check;
ALTER TABLE comp_off_requests ADD CONSTRAINT comp_off_requests_status_check
    CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'));
ALTER TABLE comp_off_requests ADD COLUMN cancelled_at TIMESTAMPTZ;
-- HR decides (reviewed_at set) only APPROVED and REJECTED requests.
ALTER TABLE comp_off_requests DROP CONSTRAINT ck_comp_off_requests_decided;
ALTER TABLE comp_off_requests ADD CONSTRAINT ck_comp_off_requests_decided
    CHECK ((status IN ('PENDING', 'CANCELLED')) = (reviewed_at IS NULL));
-- A cancelled request, like a rejected one, lets the day be asked for again.
DROP INDEX ux_comp_off_requests_active_day;
CREATE UNIQUE INDEX ux_comp_off_requests_active_day
    ON comp_off_requests (employee_id, work_date) WHERE status NOT IN ('REJECTED', 'CANCELLED');

-- 2. Personal details the employee keeps up to date (through HR approval).
ALTER TABLE employees
    ADD COLUMN address VARCHAR(300),
    ADD COLUMN emergency_contact_name VARCHAR(100),
    ADD COLUMN emergency_contact_phone VARCHAR(20),
    ADD COLUMN bank_account_name VARCHAR(100),
    ADD COLUMN bank_account_number VARCHAR(18)
        CHECK (bank_account_number IS NULL OR bank_account_number ~ '^[0-9]{9,18}$'),
    ADD COLUMN bank_ifsc VARCHAR(11)
        CHECK (bank_ifsc IS NULL OR bank_ifsc ~ '^[A-Z]{4}0[A-Z0-9]{6}$');

-- 3. An employee's request to change those details. "changes" holds only the
--    fields asked for (new values); "previous" the values at the time, so HR
--    sees old and new side by side. HR approves (applied once) or rejects.
CREATE TABLE profile_change_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    changes JSONB NOT NULL,
    previous JSONB NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    reviewed_by BIGINT REFERENCES app_users(id),
    reviewed_at TIMESTAMPTZ,
    review_note VARCHAR(500),
    cancelled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_profile_change_requests_decided
        CHECK ((status IN ('PENDING', 'CANCELLED')) = (reviewed_at IS NULL))
);
-- At most one waiting request per employee.
CREATE UNIQUE INDEX ux_profile_change_requests_pending
    ON profile_change_requests (employee_id) WHERE status = 'PENDING';
CREATE INDEX idx_profile_change_requests_status ON profile_change_requests (status, created_at);

-- 4. New notifications:
--   LEAVE_CANCELLED            (HR) an employee cancelled pending leave
--   COMP_OFF_CANCELLED         (HR) an employee cancelled a pending Comp-Off request
--   PROFILE_CHANGE_REQUESTED   (HR) an employee asked to change personal details
--   PROFILE_CHANGE_APPROVED    the employee's change was approved
--   PROFILE_CHANGE_REJECTED    the employee's change was rejected
ALTER TABLE notifications DROP CONSTRAINT ck_notifications_type;
ALTER TABLE notifications ADD CONSTRAINT ck_notifications_type
    CHECK (type IN ('LEAVE_APPROVED', 'LEAVE_REJECTED', 'TIMESHEET_APPROVED', 'TIMESHEET_REJECTED',
                    'PAYSLIP_PUBLISHED', 'DOCUMENT_PUBLISHED',
                    'SCHEDULE_CHANGED', 'COMP_OFF_APPROVED', 'COMP_OFF_REJECTED',
                    'TIMESHEET_REMINDER',
                    'LEAVE_BALANCE_UPDATED', 'HOLIDAYS_UPDATED',
                    'LEAVE_PENDING_REMINDER', 'COMP_OFF_PENDING_REMINDER', 'PENDING_APPROVALS_REMINDER',
                    'LEAVE_CANCELLED', 'COMP_OFF_CANCELLED',
                    'PROFILE_CHANGE_REQUESTED', 'PROFILE_CHANGE_APPROVED', 'PROFILE_CHANGE_REJECTED'));

-- 5. The HR Activity screen lists the audit log newest first, by kind.
CREATE INDEX idx_audit_history_entity ON audit_history (entity_type, created_at);
