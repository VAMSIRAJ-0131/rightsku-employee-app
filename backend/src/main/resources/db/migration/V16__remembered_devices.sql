-- "Stay signed in" on the Android app. Additive only.
--
-- When someone signs in on the phone app, the server issues a long random
-- refresh token for that phone. Only a SHA-256 hash of it is stored here; the
-- token itself lives encrypted on the phone (Android Keystore). The app uses it
-- to get a new short-lived sign-in token without asking for the password again.
--
-- It stops working when the person taps Log out (revoked_at), after it has not
-- been used for the configured time (expires_at, extended on each use), when
-- the password changes or HR resets it (session_version no longer matches the
-- account's), or when the account is deactivated.

CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    session_version INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);

CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);
