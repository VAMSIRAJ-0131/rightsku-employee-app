-- Push notifications to the phone app, and weekly timesheet reminders. Additive only.
--
-- push_tokens: the Firebase Cloud Messaging token of each phone where someone
-- is signed in to the app. A token belongs to one account at a time (the
-- last one to sign in on that phone); it is removed at Log out, or when
-- Firebase says it is no longer valid.

CREATE TABLE push_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    token VARCHAR(4096) NOT NULL UNIQUE,
    platform VARCHAR(20) NOT NULL DEFAULT 'android' CHECK (platform IN ('android', 'ios')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_push_tokens_user ON push_tokens (user_id);

-- A new notification: "please submit your timesheet" (Mondays, 11:00 and 21:00).
ALTER TABLE notifications DROP CONSTRAINT ck_notifications_type;
ALTER TABLE notifications ADD CONSTRAINT ck_notifications_type
    CHECK (type IN ('LEAVE_APPROVED', 'LEAVE_REJECTED', 'TIMESHEET_APPROVED', 'TIMESHEET_REJECTED',
                    'PAYSLIP_PUBLISHED', 'DOCUMENT_PUBLISHED',
                    'SCHEDULE_CHANGED', 'COMP_OFF_APPROVED', 'COMP_OFF_REJECTED',
                    'TIMESHEET_REMINDER'));
